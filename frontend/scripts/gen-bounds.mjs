// Reads docs/openapi.json and writes src/api/bounds.ts: min / max / default / description for every Scenario field,
// so the form validates exactly like the API. Run through `npm run gen:api`.
import { readFileSync, writeFileSync } from 'node:fs'

const spec = JSON.parse(readFileSync(new URL('../../docs/openapi.json', import.meta.url), 'utf8'))
const props = spec.components.schemas.Scenario.properties
const out = {}
for (const [name, p] of Object.entries(props)) {
  const variants = p.anyOf ?? [p]
  const num = variants.find((v) => v.type === 'number' || v.type === 'integer')
  const en = variants.find((v) => v.enum) ?? (p.enum ? p : undefined)
  const entry = { default: p.default ?? null, description: p.description ?? '' }
  if (num) {
    entry.kind = 'number'
    entry.integer = num.type === 'integer'
    entry.min = num.minimum ?? num.exclusiveMinimum ?? null
    entry.minExclusive = num.exclusiveMinimum !== undefined
    entry.max = num.maximum ?? num.exclusiveMaximum ?? null
    entry.maxExclusive = num.exclusiveMaximum !== undefined
    entry.nullable = variants.some((v) => v.type === 'null')
  } else if (en) {
    entry.kind = 'enum'
    entry.options = en.enum
  }
  out[name] = entry
}
const body = `// GENERATED by scripts/gen-bounds.mjs from docs/openapi.json. Do not edit.\nexport type FieldBound = {\n  kind: 'number' | 'enum'\n  default: number | string | null\n  description: string\n  integer?: boolean\n  min?: number | null\n  minExclusive?: boolean\n  max?: number | null\n  maxExclusive?: boolean\n  nullable?: boolean\n  options?: string[]\n}\nexport const SCENARIO_BOUNDS: Record<string, FieldBound> = ${JSON.stringify(out, null, 2)}\n`
writeFileSync(new URL('../src/api/bounds.ts', import.meta.url), body)
console.log('bounds for', Object.keys(out).length, 'fields')
